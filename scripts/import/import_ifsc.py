@dataclass(slots=True)
class Row:
    ifsc: str
    inst_key: str
    branch: str
    address: str | None
    city: str | None
    district: str | None
    state: str | None
    postal_code: str | None
    phone: str | None
    micr: str | None


def clean(value: object) -> str:
    """Collapse whitespace runs and trim; the source mixes tabs and double spaces."""
    return re.sub(r"\s+", " ", str(value or "")).strip()


def sql_str(value: str | None) -> str:
    if value is None:
        return "NULL"
    escaped = value.replace("\\", "\\\\").replace("'", "\\'")
    return f"'{escaped}'"


def institution_key(name: str) -> str:
    """Case/space-insensitive identity so one bank cannot split in two."""
    return clean(name).upper()


def load_rows(path: Path) -> tuple[list[Row], dict[str, str], Counter]:
    """Parse IFSC.csv into Rows plus the inst_key -> display name map."""
    rows: list[Row] = []
    names: dict[str, Counter[str]] = {}
    seen: set[str] = set()
    stats: Counter[str] = Counter()
    skipped: list[tuple[str, str]] = []

    with open(path, newline="", encoding="utf-8") as fh:
        for raw in csv.DictReader(fh):
            ifsc = clean(raw.get("IFSC")).upper()
            if not IFSC_RE.fullmatch(ifsc):
                skipped.append((ifsc, "malformed code"))
                continue
            if ifsc in seen:
                skipped.append((ifsc, "duplicate code"))
                continue
            seen.add(ifsc)

            name = clean(raw.get("BANK"))
            if not name:
                name = BANK_NAME_OVERRIDES.get(ifsc[:4], "")
                if name:
                    stats["names_from_override"] += 1
            if not name:
                skipped.append((ifsc, "no bank name"))
                continue
            names.setdefault(institution_key(name), Counter())[name] += 1

            address = clean(raw.get("ADDRESS")) or None
            if address and len(address) > 300:  # bank_branch.address is varchar(300)
                address = address[:300]
                stats["address_truncated"] += 1
            pin = PIN_RE.search(address) if address else None
            if pin:
                stats["pincodes"] += 1

            micr = clean(raw.get("MICR"))
            if MICR_RE.fullmatch(micr):
                stats["micr"] += 1
            else:
                micr = None

            rows.append(
                Row(
                    ifsc=ifsc,
                    inst_key=institution_key(name),
                    branch=(clean(raw.get("BRANCH")) or "HEAD OFFICE")[:200],
                    address=address,
                    city=clean(raw.get("CITY"))[:100] or None,
                    district=clean(raw.get("DISTRICT"))[:100] or None,
                    state=clean(raw.get("STATE"))[:100] or None,
                    postal_code=pin.group(1) if pin else None,
                    phone=clean(raw.get("CONTACT"))[:40] or None,
                    micr=micr,
                )
            )

    if skipped:
        print(f"skipped {len(skipped)} rows, e.g. {skipped[:5]}")
    # Display name: the spelling used by most rows, longest spelling on a tie.
    display = {key: max(c.most_common(), key=lambda kv: (kv[1], len(kv[0])))[0]
               for key, c in names.items()}
    return rows, display, stats


# Institution identity -> type, for the overridden (non-bank) participants.
TYPE_BY_NAME: dict[str, str] = {
    institution_key(BANK_NAME_OVERRIDES[code]): inst_type
    for code, inst_type in INSTITUTION_TYPE_OVERRIDES.items()
}


def load_regulator_types(rows: list[Row], path: Path) -> dict[str, str]:
    """inst_key -> banks.json regulator class, via the entry's representative IFSC.

    banks.json keys banks by their 4-letter code and carries no display name, so
    the code's representative IFSC is the join back to the institution name used
    in IFSC.csv. Missing file or unresolvable codes simply yield fewer entries.
    """
    if not path.exists():
        print(f"bank master {path} not found, regulator classes skipped")
        return {}
    by_ifsc = {row.ifsc: row.inst_key for row in rows}
    votes: dict[str, Counter[str]] = {}
    with open(path, encoding="utf-8") as fh:
        master = json.load(fh)
    for entry in master.values():
        key = by_ifsc.get(entry.get("ifsc") or "")
        regulator = entry.get("type")
        if key and regulator:
            votes.setdefault(key, Counter())[regulator] += 1
    return {key: counts.most_common(1)[0][0] for key, counts in votes.items()}


def institution_type(inst_key: str, regulator_types: dict[str, str]) -> str:
    if inst_key in TYPE_BY_NAME:
        return TYPE_BY_NAME[inst_key]
    return REGULATOR_TYPE_MAP.get(regulator_types.get(inst_key, ""), "BANK")


def write_staging(fh, rows: list[Row], display: dict[str, str]) -> None:
    """Stream the per-IFSC staging rows in 1000-row INSERT batches."""
    fh.write(
        "-- -----------------------------------------------------------------\n"
        "-- Staging table: one row per IFSC code, joined back by natural keys.\n"
        "-- -----------------------------------------------------------------\n"
        "CREATE TEMPORARY TABLE tmp_ifsc (\n"
        "    ifsc        VARCHAR(11)  NOT NULL PRIMARY KEY,\n"
        "    inst_name   VARCHAR(200) NOT NULL,\n"
        "    branch_name VARCHAR(200) NOT NULL,\n"
        "    address     VARCHAR(300) NULL,\n"
        "    city        VARCHAR(100) NULL,\n"
        "    district    VARCHAR(100) NULL,\n"
        "    state       VARCHAR(100) NULL,\n"
        "    postal_code VARCHAR(20)  NULL,\n"
        "    phone       VARCHAR(40)  NULL,\n"
        "    micr        VARCHAR(9)   NULL,\n"
        "    KEY idx_tmp_ifsc_inst (inst_name)\n"
        ") ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;\n"
    )
    batch: list[str] = []
    for row in rows:
        batch.append(
            f"({sql_str(row.ifsc)},{sql_str(display[row.inst_key])},"
            f"{sql_str(row.branch)},{sql_str(row.address)},{sql_str(row.city)},"
            f"{sql_str(row.district)},{sql_str(row.state)},"
            f"{sql_str(row.postal_code)},{sql_str(row.phone)},"
            f"{sql_str(row.micr)})"
        )
        if len(batch) >= 1000:
            fh.write("INSERT INTO tmp_ifsc VALUES\n  " + ",\n  ".join(batch) + ";\n")
            batch = []
    if batch:
        fh.write("INSERT INTO tmp_ifsc VALUES\n  " + ",\n  ".join(batch) + ";\n")


def write_sql(rows: list[Row], display: dict[str, str], regulator_types: dict[str, str],
              out_path: Path) -> Counter:
    counters: Counter[str] = Counter()
    out_path.parent.mkdir(parents=True, exist_ok=True)

    with open(out_path, "w", encoding="utf-8") as fh:
        fh.write(
            "-- import_ifsc.sql (generated by scripts/import/import_ifsc.py)\n"
            f"-- India IFSC directory from the Razorpay IFSC dataset ({SOURCE_URL}),\n"
            "-- built from the RBI NEFT/RTGS IFSC registers and the NPCI NACH lists.\n"
            f"-- Rows: {len(rows)} IFSC codes, {len(display)} institutions.\n"
            "-- Re-runnable: the pre-clean removes a previous run first.\n"
            "SET NAMES utf8mb4;\n"
            "\n"
            "-- -----------------------------------------------------------------\n"
            "-- Provenance + country rows (guarded, re-runnable).\n"
            "-- -----------------------------------------------------------------\n"
            "START TRANSACTION;\n"
            "INSERT INTO data_source (name, source_type, provider, source_url, license,\n"
            "                         commercial_use, redistribution_allowed, storage_allowed, status)\n"
            f"SELECT {sql_str(SOURCE_NAME)}, 'PUBLIC', {sql_str(SOURCE_PROVIDER)},\n"
            f"       {sql_str(SOURCE_URL)}, {sql_str(SOURCE_LICENSE)}, TRUE, TRUE, TRUE, 'ACTIVE'\n"
            "WHERE NOT EXISTS (SELECT 1 FROM data_source WHERE name = "
            f"{sql_str(SOURCE_NAME)});\n"
            "COMMIT;\n"
            "-- Keep the provenance text current for rows created by an older run.\n"
            "UPDATE data_source SET provider = "
            f"{sql_str(SOURCE_PROVIDER)}\n"
            f"WHERE name = {sql_str(SOURCE_NAME)} AND provider <> {sql_str(SOURCE_PROVIDER)};\n"
            "SET @src_id := (SELECT id FROM data_source WHERE name = "
            f"{sql_str(SOURCE_NAME)} ORDER BY id LIMIT 1);\n"
            "\n"
            "START TRANSACTION;\n"
            "INSERT INTO country (iso2, iso3, numeric_code, name_en, name_local,\n"
            "                     currency_code, swift_supported, iban_supported,\n"
            "                     local_identifier_type, status)\n"
            "SELECT 'IN', 'IND', '356', 'India', '印度', 'INR', TRUE, TRUE, 'IFSC', 'ACTIVE'\n"
            "WHERE NOT EXISTS (SELECT 1 FROM country WHERE iso2 = 'IN');\n"
            "COMMIT;\n"
            "SET @in_id := (SELECT id FROM country WHERE iso2 = 'IN' LIMIT 1);\n"
            "\n"
            "-- -----------------------------------------------------------------\n"
            "-- Defensive pre-clean: drop the rows of a previous run (IN IFSC\n"
            "-- identifiers, then their orphan branches and institutions). An IN\n"
            "-- institution that still carries other identifiers is left alone.\n"
            "-- -----------------------------------------------------------------\n"
            "START TRANSACTION;\n"
            "DELETE bi FROM bank_identifier bi\n"
            "WHERE bi.identifier_type = 'IFSC' AND bi.country_code = 'IN';\n"
            "DELETE bb FROM bank_branch bb\n"
            "JOIN financial_institution fi ON fi.id = bb.institution_id\n"
            "WHERE fi.country_id = @in_id\n"
            "  AND NOT EXISTS (SELECT 1 FROM bank_identifier bi WHERE bi.branch_id = bb.id);\n"
            "DELETE fi FROM financial_institution fi\n"
            "WHERE fi.country_id = @in_id\n"
            "  AND NOT EXISTS (SELECT 1 FROM bank_identifier bi WHERE bi.institution_id = fi.id)\n"
            "  AND NOT EXISTS (SELECT 1 FROM bank_branch bb WHERE bb.institution_id = fi.id);\n"
            "COMMIT;\n"
            "\n"
        )

        write_staging(fh, rows, display)

        # Institutions come straight from the Python-side assembly: one row per
        # (name, country) so a bank spelled two ways cannot split the directory.
        fh.write("\nSTART TRANSACTION;\n")
        inst_batch: list[str] = []
        type_counts: Counter[str] = Counter()
        for key in display:
            name = display[key]
            inst_type = institution_type(key, regulator_types)
            type_counts[inst_type] += 1
            # name_local/short_name mirror the V18 backfill: the display chain
            # (breadcrumb, v1/banks, detail page) reads short_name, and a
            # rebuilt row must not come back blank after the pre-clean.
            inst_batch.append(
                f"({sql_str(name)},{sql_str(name)},{sql_str(name)},"
                f"{sql_str(clean(name).lower())},{sql_str(name[:64])},"
                f"@in_id,{sql_str(inst_type)},'ACTIVE')"
            )
        for i in range(0, len(inst_batch), 500):
            fh.write(
                "INSERT INTO financial_institution (legal_name, name_en, name_local,\n"
                "                                   name_norm, short_name, country_id,\n"
                "                                   institution_type, status) VALUES\n  "
                + ",\n  ".join(inst_batch[i:i + 500]) + ";\n"
            )
        counters["institutions"] = len(inst_batch)
        counters.update(type_counts)

        fh.write(
            "\n"
            "-- Branch points: one row per (institution, branch, city, address). The\n"
            "-- key matches the identifier join below, so the 82 codes that reuse\n"
            "-- another code's identity collapse here instead of multiplying the\n"
            "-- back-fill; the columns outside the key take MIN() (MICR included: the\n"
            "-- 24 identities whose codes disagree keep one value).\n"
            "INSERT INTO bank_branch (institution_id, branch_name, address, city, province,\n"
            "                         state, postal_code, phone, micr, status)\n"
            "SELECT fi.id, t.branch_name, t.address, t.city, MIN(t.district), MIN(t.state),\n"
            "       MIN(t.postal_code), MIN(t.phone), MIN(t.micr), 'ACTIVE'\n"
            "FROM tmp_ifsc t\n"
            "JOIN financial_institution fi\n"
            "  ON fi.name_en = t.inst_name AND fi.country_id = @in_id\n"
            "GROUP BY fi.id, t.branch_name, t.address, t.city;\n"
            "COMMIT;\n"
            "\n"
            "-- Throwaway join index for the identifier back-fill (DDL commits implicitly).\n"
            "ALTER TABLE bank_branch ADD INDEX idx_ifsc_import_join\n"
            "    (institution_id, branch_name, city, address);\n"
            "\n"
            "START TRANSACTION;\n"
            "-- IFSC identifiers, one per staged code, pinned to one branch row.\n"
            "INSERT INTO bank_identifier (institution_id, branch_id, identifier_type,\n"
            "                             identifier_value, country_code, status, source_id)\n"
            "SELECT fi.id, MIN(bb.id), 'IFSC', t.ifsc, 'IN', 'ACTIVE', @src_id\n"
            "FROM tmp_ifsc t\n"
            "JOIN financial_institution fi\n"
            "  ON fi.name_en = t.inst_name AND fi.country_id = @in_id\n"
            "JOIN bank_branch bb\n"
            "  ON bb.institution_id = fi.id\n"
            " AND bb.branch_name = t.branch_name\n"
            " AND bb.city <=> t.city\n"
            " AND bb.address <=> t.address\n"
            "GROUP BY t.ifsc, fi.id;\n"
            "COMMIT;\n"
            "\n"
            "ALTER TABLE bank_branch DROP INDEX idx_ifsc_import_join;\n"
            "DROP TEMPORARY TABLE tmp_ifsc;\n"
            "\n"
            "-- Slug back-fill for the new institutions (V17 rule, IN scope).\n"
            "UPDATE financial_institution fi\n"
            "JOIN (\n"
            "    SELECT x.id, x.candidate,\n"
            "           ROW_NUMBER() OVER (PARTITION BY x.candidate ORDER BY x.is_rule, x.id) AS rn\n"
            "    FROM (\n"
            "        SELECT fi2.id,\n"
            "               REGEXP_REPLACE(\n"
            "                   LEFT(REGEXP_REPLACE(LOWER(TRIM(fi2.name_en)), '[^0-9a-z]+', '-'), 100),\n"
            "                   '-+$', '') AS candidate,\n"
            "               1 AS is_rule\n"
            "        FROM financial_institution fi2\n"
            "        WHERE fi2.slug IS NULL\n"
            "          AND fi2.country_id = @in_id\n"
            "          AND fi2.name_en IS NOT NULL AND fi2.name_en <> ''\n"
            "        UNION ALL\n"
            "        SELECT id, slug, 0 AS is_rule\n"
            "        FROM financial_institution\n"
            "        WHERE slug IS NOT NULL\n"
            "    ) x\n"
            "    WHERE x.candidate IS NOT NULL AND x.candidate <> ''\n"
            ") ranked ON ranked.id = fi.id\n"
            "SET fi.slug = CASE\n"
            "    WHEN ranked.rn = 1 THEN ranked.candidate\n"
            "    ELSE CONCAT(LEFT(ranked.candidate, 120), '-', ranked.id)\n"
            "END;\n"
        )

        # Slugs already published by the static dataset stay theirs: a colliding
        # IN row is a different institution from the static page and must not
        # shadow it.
        static_slugs = sorted(website_static_slugs() - set(STATIC_SLUG_FOLDS))
        if static_slugs:
            reserved = ", ".join(f"'{slug}'" for slug in static_slugs)
            fh.write(
                "\n"
                "-- Website slug contract: never steal a published static slug.\n"
                "UPDATE financial_institution\n"
                "SET slug = CONCAT(LEFT(slug, 120), '-', id)\n"
                "WHERE country_id = @in_id\n"
                f"  AND slug IN ({reserved});\n"
            )

        # ... while the four Indian static records fold onto their directory row.
        # A non-IN row can already hold one of these slugs from the V17 backfill
        # (e.g. the AU State Bank of India owns state-bank-of-india on the prod
        # database), which trips uk_financial_institution_slug at the fold.
        # Move those rows aside with the V17 id suffix first: the published
        # Indian static URL keeps its slug and both rows stay addressable.
        owned_slugs = ", ".join(f"'{slug}'" for slug in STATIC_SLUG_FOLDS)
        fh.write(
            "\n-- Static slug contract: free the slugs held outside India first.\n"
            "UPDATE financial_institution\n"
            "SET slug = CONCAT(LEFT(slug, 120), '-', id)\n"
            "WHERE country_id <> @in_id\n"
            f"  AND slug IN ({owned_slugs});\n"
        )
        fh.write("\n-- Static slug contract (India), idempotent.\n")
        for slug, name in STATIC_SLUG_FOLDS.items():
            fh.write(
                f"UPDATE financial_institution SET slug = '{slug}'\n"
                f"WHERE country_id = @in_id AND UPPER(name_en) = {sql_str(name)};\n"
            )

        fh.write(
            "\n"
            "-- Verification counts.\n"
            "SELECT 'IN institutions' AS metric, COUNT(*) AS n\n"
            "  FROM financial_institution WHERE country_id = @in_id\n"
            "UNION ALL SELECT 'IN branches', COUNT(*)\n"
            "  FROM bank_branch bb JOIN financial_institution fi ON fi.id = bb.institution_id\n"
            "  WHERE fi.country_id = @in_id\n"
            "UNION ALL SELECT 'IFSC codes', COUNT(*)\n"
            "  FROM bank_identifier WHERE identifier_type = 'IFSC' AND country_code = 'IN'\n"
            "UNION ALL SELECT 'IFSC codes without branch', COUNT(*)\n"
            "  FROM bank_identifier\n"
            "  WHERE identifier_type = 'IFSC' AND country_code = 'IN' AND branch_id IS NULL;\n"
        )

    return counters


def main() -> None:
    here = Path(__file__).resolve().parent
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--data", type=Path, default=here.parent.parent / "data" / "ifsc",
                        help="directory containing IFSC.csv")
    parser.add_argument("--out", type=Path, default=None,
                        help="output SQL path (default <data>/import_ifsc.sql)")
    args = parser.parse_args()

    csv_path = args.data / "IFSC.csv"
    rows, display, stats = load_rows(csv_path)
    # Branch identity matches the branch INSERT ... GROUP BY in write_sql.
    stats["distinct branches"] = len({(r.inst_key, r.branch, r.address, r.city)
                                      for r in rows})
    regulator_types = load_regulator_types(rows, args.data / "banks.json")

    out_path = args.out or (args.data / "import_ifsc.sql")
    counters = write_sql(rows, display, regulator_types, out_path)

    size_mb = out_path.stat().st_size / 1024 / 1024
    print("\n===== Import summary =====")
    print(f"source: {csv_path}")
    print(f"output: {out_path} ({size_mb:.1f} MB)")
    print(f"rows: {len(rows)} IFSC codes")
    print(f"institutions: {counters['institutions']}")
    for inst_type in ("BANK", "CREDIT_UNION", "DIGITAL_BANK", "PAYMENT_INSTITUTION", "OTHER"):
        if counters.get(inst_type):
            print(f"  {inst_type}: {counters[inst_type]}")
    print(f"branch points: {stats['distinct branches']}")
    print(f"bank names resolved via overrides: {stats['names_from_override']}")
    print(f"regulator classes resolved from banks.json: {len(regulator_types)}")
    print(f"rows with a MICR: {stats['micr']}")
    print(f"rows with a PIN extracted: {stats['pincodes']}")
    if stats["address_truncated"]:
        print(f"addresses truncated to 300 chars: {stats['address_truncated']}")


if __name__ == "__main__":
    main()
